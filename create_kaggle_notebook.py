                "        comb = f'{t_str} {b_str}'.strip()\n",
                "        words = comb.split()\n",
                "        cap_count = float(sum(1 for w in words if w.isupper() and len(w) > 1 and w.isalpha()))\n",
                "        p_count = float(sum(1 for ch in comb if ch in self.punct_set))\n",
                "        d_ratio = float(sum(1 for ch in comb if ch.isdigit()) / max(1, len(comb)))\n",
                "        return [float(len(t_str)), float(len(b_str)), cap_count, p_count, d_ratio]\n",
                "\n",
                "    def transform(self, X):\n",
                "        titles = X['title'].tolist() if 'title' in X.columns else [''] * len(X)\n",
                "        texts = X['text'].tolist() if 'text' in X.columns else X.iloc[:, 0].tolist()\n",
                "        return np.array([self._extract_single(t, b) for t, b in zip(titles, texts)], dtype=np.float32)\n",
