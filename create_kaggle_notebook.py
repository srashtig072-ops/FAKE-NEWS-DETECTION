                "FULL_PUNCT = string.punctuation + '！？。，、“”‘’《》（）…—：；【】—～·'\n",
                "\n",
                "class TextPreprocessor:\n",
                "    def __init__(self):\n",
                "        self.lemmatizer = WordNetLemmatizer()\n",
                "        self.url_pattern = re.compile(r'https?://\\S+|www\\.\\S+|t\\.cn/\\S+|sinaurl\\.cn/\\S+')\n",
                "        self.html_pattern = re.compile(r'<.*?>')\n",
                "        self.num_pattern = re.compile(r'\\d+')\n",
                "        self.punct_pattern = re.compile(f'[{re.escape(FULL_PUNCT)}]')\n",
                "        self.cn_char_pattern = re.compile(r'[\\u4e00-\\u9fff]')\n",
                "        self.ws_pattern = re.compile(r'\\s+')\n",
                "\n",
                "    def clean_text(self, text: str) -> str:\n",
                "        if not text or pd.isna(text):\n",
                "            return ''\n",
                "        text = str(text)\n",
                "        text = self.url_pattern.sub(' ', text)\n",
                "        text = self.html_pattern.sub(' ', text)\n",
                "        text = self.num_pattern.sub(' ', text)\n",
                "        \n",
                "        if self.cn_char_pattern.search(text):\n",
                "            text = self.punct_pattern.sub(' ', text)\n",
                "            words = jieba.cut(text)\n",
                "            tokens = [w.strip() for w in words if len(w.strip()) > 1 and w.strip() not in CHINESE_STOPWORDS]\n",
                "        else:\n",
                "            text = text.lower()\n",
                "            text = self.punct_pattern.sub(' ', text)\n",
                "            tokens = [self.lemmatizer.lemmatize(w) for w in text.split() if w not in EN_STOPWORDS and len(w) > 1]\n",
                "            \n",
                "        return self.ws_pattern.sub(' ', ' '.join(tokens)).strip()\n",
                "\n",
                "    def transform(self, texts):\n",
                "        return [self.clean_text(t) for t in texts]\n",
                "\n",
                "class HandcraftedLinguisticExtractor(BaseEstimator, TransformerMixin):\n",
                "    def __init__(self):\n",
                "        self.feature_names = ['title_length', 'article_length', 'capital_words_count', 'punctuation_count', 'digit_ratio']\n",
                "        self.punct_set = set(FULL_PUNCT)\n",
                "\n",
                "    def fit(self, X, y=None):\n",
                "        return self\n",
                "\n",
                "    def _extract_single(self, title, text):\n",
                "        t_str = str(title) if title is not None and not pd.isna(title) else ''\n",
